public class Platos {
    public String id_plato = "id_plato";
    public String nombre = "nombre";
    public String categoria = "categoria";
    public String precio = "precio";

    public Platos() {
    }

    public Platos(String id_plato, String nombre, String categoria, String precio) {
        this.id_plato = id_plato;
        this.nombre = nombre;
        this.categoria = categoria;
        this.precio = precio;
    }
}
